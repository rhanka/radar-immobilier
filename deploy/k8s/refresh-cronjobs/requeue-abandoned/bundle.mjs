// Builds requeue-abandoned.bundle.mjs from the TypeScript operator command.
// The bundle is the ONLY requeue code shipped to the frozen prod image: it
// inlines api/src/scripts/refresh-requeue-abandoned.ts plus the existing
// coverage module it imports, so no second implementation exists. Regenerate
// with: make -f deploy/k8s/refresh-cronjobs/refresh-018.mk bundle-requeue-abandoned ENV=ci
// esbuild is pinned to the same version as api/Dockerfile (0.25.12).

import { build } from "esbuild";

await build({
  entryPoints: ["api/src/scripts/refresh-requeue-abandoned.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node24",
  outfile: "deploy/k8s/refresh-cronjobs/requeue-abandoned/requeue-abandoned.bundle.mjs",
  banner: { js: "// GENERATED by bundle.mjs (esbuild 0.25.12) from api/src/scripts/refresh-requeue-abandoned.ts — do not edit." },
  plugins: [{
    name: "ext",
    setup(b) {
      b.onResolve({ filter: /^[^./]/ }, (a) =>
        a.path.startsWith("@radar/") ? null : { path: a.path, external: true });
    },
  }],
});
console.log("requeue-abandoned.bundle.mjs written");
