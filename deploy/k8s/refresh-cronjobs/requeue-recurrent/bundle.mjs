// Builds requeue-recurrent.bundle.mjs from the TypeScript recurrent command.
// Same pattern as ../requeue-abandoned/bundle.mjs: the bundle inlines
// api/src/scripts/refresh-requeue-recurrent.ts (seat probe + requeue) so it
// runs on the frozen release image, resolving the image's own node_modules.
// Regenerate with: make -f deploy/k8s/refresh-cronjobs/refresh-018.mk
// bundle-requeue-recurrent ENV=ci (esbuild 0.25.12, pinned as in api/Dockerfile).

import { build } from "esbuild";

await build({
  entryPoints: ["api/src/scripts/refresh-requeue-recurrent.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node24",
  outfile: "deploy/k8s/refresh-cronjobs/requeue-recurrent/requeue-recurrent.bundle.mjs",
  banner: { js: "// GENERATED by bundle.mjs (esbuild 0.25.12) from api/src/scripts/refresh-requeue-recurrent.ts — do not edit." },
  plugins: [{
    name: "ext",
    setup(b) {
      b.onResolve({ filter: /^[^./]/ }, (a) =>
        a.path.startsWith("@radar/") ? null : { path: a.path, external: true });
    },
  }],
});
console.log("requeue-recurrent.bundle.mjs written");
