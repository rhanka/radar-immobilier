#!/usr/bin/env bash
# Hermetic render tests of the recurrent requeue CronJob (refresh-018.mk):
# no cluster. Renders both overlays with a fake digest and checks guards.
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
MK="$HERE/../refresh-018.mk"
PASS=0 FAIL=0
ok() { PASS=$((PASS + 1)); echo "ok: $1"; }
bad() { FAIL=$((FAIL + 1)); echo "FAIL: $1" >&2; }

T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
DIGEST="ghcr.io/rhanka/radar-api@sha256:$(printf 'a%.0s' $(seq 64))"

render() { # $1=ENV $2=out
  make -s -f "$MK" render-requeue-recurrent REQUEUE_IMAGE_REF="$DIGEST" \
    REQUEUE_RENDER_OUT="$2" ENV="$1" >"$T/out" 2>&1
}

if render preprod "$T/preprod.yaml" && grep -q '^  namespace: radar-immobilier-preprod$' "$T/preprod.yaml" \
  && grep -q 'schedule: 30 4' "$T/preprod.yaml" \
  && grep -q 'concurrencyPolicy: Forbid' "$T/preprod.yaml" \
  && grep -q 'radar-docs-s3-credentials' "$T/preprod.yaml" \
  && grep -q 'requeue-recurrent.bundle.mjs' "$T/preprod.yaml"; then
  ok "preprod render: namespace, daily 04:30 slot, Forbid, preprod S3 secret, bundle"
else bad "preprod render ($(cat "$T/out"))"; fi

if [ -f "$T/preprod.yaml" ] && kubectl create --dry-run=client --validate=false -f "$T/preprod.yaml" >/dev/null 2>&1; then
  ok "preprod render parses (kubectl dry-run=client)"
else bad "preprod render does not parse"; fi

if render prod "$T/prod.yaml" && grep -q '^  namespace: radar-immobilier$' "$T/prod.yaml" \
  && grep -q 'schedule: 30 3' "$T/prod.yaml" \
  && grep -q 'radar-scrape-s3-credentials' "$T/prod.yaml" \
  && kubectl create --dry-run=client --validate=false -f "$T/prod.yaml" >/dev/null 2>&1; then
  ok "prod render: namespace, daily 03:30 slot, prod S3 secret, parses"
else bad "prod render ($(cat "$T/out"))"; fi

if render ci "$T/ci.yaml"; then bad "ENV=ci accepted"
else grep -q "ENV=preprod or ENV=prod is required" "$T/out" && ok "ENV other than preprod/prod refused" || bad "ENV guard: wrong refusal"; fi

if make -s -f "$MK" render-requeue-recurrent REQUEUE_IMAGE_REF="ghcr.io/rhanka/radar-api:latest" \
  REQUEUE_RENDER_OUT="$T/tag.yaml" ENV=preprod >"$T/out" 2>&1; then bad "non-digest image accepted"
else grep -q "immutable digest" "$T/out" && ok "non-digest image refused" || bad "image guard: wrong refusal"; fi

test -s "$HERE/requeue-recurrent.bundle.mjs" && grep -q "GENERATED by bundle.mjs" "$HERE/requeue-recurrent.bundle.mjs" \
  && ok "committed bundle present and marked generated" || bad "bundle missing"

echo "requeue-recurrent.test.sh: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
